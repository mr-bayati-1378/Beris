export async function POST(request: NextRequest) {
  try {
    // بررسی admin session
    const cookieStore = await cookies();
    const adminSession = cookieStore.get('admin-session');
    
    if (!adminSession || adminSession.value !== 'authenticated') {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    // دریافت داده‌ها از Google Sheets
    const sheetsData = await fetchFromGoogleSheets();
    
    if (!sheetsData || sheetsData.length === 0) {
      return NextResponse.json({ error: 'داده‌ای از Google Sheets دریافت نشد' }, { status: 400 });
    }

    const results = {
      updated: 0,
      created: 0,
      errors: [] as string[],
      totalProcessed: sheetsData.length
    };

    // پردازش هر محصول
    for (const row of sheetsData) {
      try {
        const [productName, priceStr, description] = row;
        
        if (!productName || !priceStr) {
          results.errors.push(`داده‌های ناقص برای: ${productName || 'نامشخص'}`);
          continue;
        }

        // تبدیل قیمت به عدد
        const price = parseFloat(priceStr.toString().replace(/[^\d.]/g, ''));
        if (isNaN(price) || price <= 0) {
          results.errors.push(`قیمت نامعتبر برای ${productName}: ${priceStr}`);
          continue;
        }

        // بررسی وجود محصول
        const existingProduct = await prisma.product.findFirst({
          where: {
            name: {
              equals: productName.toString().trim()
            }
          }
        });

        if (existingProduct) {
          // به‌روزرسانی محصول موجود
          await prisma.product.update({
            where: { id: existingProduct.id },
            data: {
              price: price,
              stock: 1000, // موجودی 1000
              description: description?.toString() || existingProduct.description,
              updatedAt: new Date()
            }
          });
          results.updated++;
        } else {
          // ایجاد محصول جدید
          const slug = productName.toString()
            .toLowerCase()
            .replace(/[^a-z0-9\u0600-\u06FF]/g, '-')
            .replace(/-+/g, '-')
            .replace(/^-|-$/g, '');

          // پیدا کردن یک دسته‌بندی پیش‌فرض
          const defaultCategory = await prisma.categoryL3.findFirst();

          if (!defaultCategory) {
            results.errors.push(`دسته‌بندی پیش‌فرض یافت نشد برای ${productName}`);
            continue;
          }

          await prisma.product.create({
            data: {
              name: productName.toString().trim(),
              slug: slug,
              price: price,
              stock: 1000, // موجودی 1000
              description: description?.toString() || '',
              categoryL3Id: defaultCategory.id,
              isActive: true
            }
          });
          results.created++;
        }
      } catch (error) {
        console.error(`خطا در پردازش محصول:`, error);
        results.errors.push(`خطا در پردازش ${row[0]}: ${error}`);
      }
    }

    return NextResponse.json({
      success: true,
      message: 'به‌روزرسانی محصولات با موفقیت انجام شد',
      results
    });

  } catch (error) {
    console.error('Error syncing products from sheets:', error);
    return NextResponse.json(
      { error: 'خطا در به‌روزرسانی محصولات' },
      { status: 500 }
    );
  }
}

async function fetchFromGoogleSheets() {
  try {
    const apiKey = process.env.GOOGLE_SHEETS_API_KEY;
    
    if (!apiKey) {
      console.log('Google Sheets API Key not found, using sample data');
      return getSampleData();
    }

    // استفاده از Google Sheets API v4 با API Key
    const sheets = google.sheets({ 
      version: 'v4', 
      auth: apiKey 
    });
    
    const response = await sheets.spreadsheets.values.get({
      spreadsheetId: SPREADSHEET_ID,
      range: RANGE,
      key: apiKey
    });

    const rows = response.data.values;
    console.log(`Successfully fetched ${rows?.length || 0} rows from Google Sheets`);
    return rows?.slice(1) || []; // حذف header row
  } catch (error) {
    console.error('Error fetching from Google Sheets:', error);
    
    // اگر Google Sheets API در دسترس نباشد، از داده‌های نمونه استفاده کن
    console.log('Using sample data instead of Google Sheets');
    return getSampleData();
  }
}

